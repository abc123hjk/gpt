'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { _electron } = require('playwright-core');
const root = path.resolve(__dirname, '..');
const testData = fs.mkdtempSync(path.join(os.tmpdir(), 'tangerine-smoke-'));
const executablePath = process.env.TANGERINE_ELECTRON || require('electron');
let app;
const pageErrors = [];
async function launch() {
  app = await _electron.launch({ executablePath, args: ['--no-sandbox', '--disable-dev-shm-usage', root], env: { ...process.env, TANGERINE_TEST_DATA: testData }, timeout: 30000 });
  app.on('window', page => page.on('pageerror', error => pageErrors.push(error.message)));
  await app.firstWindow();
  for (let i = 0; i < 100 && app.windows().length < 2; i++) await new Promise(resolve => setTimeout(resolve, 100));
  const panel = app.windows().find(page => page.url().endsWith('/panel.html'));
  const pet = app.windows().find(page => page.url().endsWith('/pet.html'));
  assert(panel && pet, 'Both desktop and panel windows are created');
  await panel.waitForFunction(() => document.getElementById('fish').textContent !== '');
  return { panel, pet };
}
async function run() {
  let { panel, pet } = await launch();
  await panel.locator('[data-action="feed"]').click();
  await panel.waitForFunction(() => document.getElementById('fish').textContent === '2');
  await panel.locator('[data-action="pet"]').click();
  assert.equal((await panel.evaluate(() => window.cat.getState())).affection, 4);
  await panel.locator('[data-action="sleep"]').click();
  await pet.screenshot({ path: path.join(root, 'assets/desktop-sleep-check.png'), omitBackground: true });
  await panel.locator('[data-action="wake"]').click();
  await panel.locator('[data-page="focus"]').click();
  await panel.locator('[data-minutes="15"]').click();
  await panel.locator('#timer-primary').click();
  await panel.locator('#timer-primary').click();
  let state = await panel.evaluate(() => window.cat.getState());
  assert.equal(state.timer.paused, true);
  assert.equal(state.timer.totalMs, 900000);
  const pausedRemaining = state.remainingMs;
  await panel.waitForTimeout(1200);
  assert.equal((await panel.evaluate(() => window.cat.getState())).remainingMs, pausedRemaining);
  await panel.locator('#timer-primary').click();
  assert.equal((await panel.evaluate(() => window.cat.getState())).timer.paused, false);
  await panel.locator('#timer-cancel').click();
  await panel.locator('#confirm-cancel').click();
  state = await panel.evaluate(() => window.cat.getState());
  assert.equal(state.timer, null);
  assert.equal(state.fish, 2);
  await panel.locator('[data-page="settings"]').click();
  await panel.locator('#scale').selectOption('1.3');
  await panel.locator('#roam').uncheck();
  await panel.locator('#alwaysOnTop').uncheck();
  const geometry = await app.evaluate(({ BrowserWindow }) => {
    const win = BrowserWindow.getAllWindows().find(win => win.webContents.getURL().endsWith('/pet.html'));
    return { size: win.getSize(), top: win.isAlwaysOnTop() };
  });
  assert.equal(geometry.size[0], 291);
  assert.equal(geometry.top, false);
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(win => win.webContents.getURL().endsWith('/panel.html')).close());
  assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().length), 2);
  await pet.evaluate(() => window.cat.panel());
  await panel.locator('[data-page="home"]').click();
  await panel.screenshot({ path: path.join(root, 'assets/desktop-interface-check.png'), fullPage: true });
  await app.close(); app = null;
  const persisted = JSON.parse(fs.readFileSync(path.join(testData, 'save.json'), 'utf8'));
  assert.equal(persisted.fish, 2);
  assert.equal(persisted.settings.scale, 1.3);
  assert.equal(persisted.settings.roam, false);
  // A due session must be credited once across two full process restarts.
  persisted.timer = { totalMs: 300000, remainingMs: 0, endsAt: Date.now() - 1000, paused: false };
  fs.writeFileSync(path.join(testData, 'save.json'), JSON.stringify(persisted));
  ({ panel } = await launch());
  state = await panel.evaluate(() => window.cat.getState());
  assert.equal(state.fish, 3); assert.equal(state.completed, 1); assert.equal(state.focusMinutes, 5);
  await app.close(); app = null;
  ({ panel } = await launch());
  state = await panel.evaluate(() => window.cat.getState());
  assert.equal(state.fish, 3); assert.equal(state.completed, 1);
  assert.deepEqual(pageErrors, []);
  console.log('Desktop smoke passed: feeding, petting, sleep/wake, start/pause/resume/cancel, window settings, hide/reopen, save, restart and one-time reward.');
  await app.close(); app = null;
}
run().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (app) await app.close(); });
